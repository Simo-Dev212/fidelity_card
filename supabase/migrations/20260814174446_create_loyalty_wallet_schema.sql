    "previousBalance" INTEGER NOT NULL,
    "newBalance" INTEGER NOT NULL,
    "reason" TEXT,
    "actorId" TEXT,
    "actorType" TEXT,
    "metadata" JSONB NOT NULL DEFAULT '{}',
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "loyalty_history_pkey" PRIMARY KEY ("id")
);

CREATE INDEX IF NOT EXISTS "loyalty_history_membershipId_idx" ON "loyalty_history"("membershipId");
CREATE INDEX IF NOT EXISTS "loyalty_history_companyId_idx" ON "loyalty_history"("companyId");
CREATE INDEX IF NOT EXISTS "loyalty_history_createdAt_idx" ON "loyalty_history"("createdAt");

-- ─────────────────────────────────────────────
-- wallet_passes
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "wallet_passes" (
    "id" TEXT NOT NULL,
    "membershipId" TEXT NOT NULL,
    "companyId" TEXT NOT NULL,
    "provider" "WalletProviderType" NOT NULL,
    "externalId" TEXT NOT NULL,
    "saveUrl" TEXT,
    "status" "WalletPassStatus" NOT NULL DEFAULT 'PENDING',
    "lastSyncAt" TIMESTAMP(3),
    "lastError" TEXT,
    "lastPayload" JSONB,
    "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "wallet_passes_pkey" PRIMARY KEY ("id")
);

CREATE UNIQUE INDEX IF NOT EXISTS "wallet_passes_membershipId_key" ON "wallet_passes"("membershipId");
CREATE INDEX IF NOT EXISTS "wallet_passes_companyId_idx" ON "wallet_passes"("companyId");
CREATE INDEX IF NOT EXISTS "wallet_passes_externalId_idx" ON "wallet_passes"("externalId");

