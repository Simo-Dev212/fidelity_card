/*
# Create Loyalty Wallet Platform Schema

## Overview
Creates the full database schema for a multi-tenant digital loyalty wallet platform.
The app is a NestJS backend using Prisma ORM with its own JWT auth (not Supabase auth).
Tables use TEXT-based CUID primary keys (generated by Prisma client) to match the Prisma schema.

## New Tables
1. `companies` — Tenant root: restaurants/brands with branding (colors, logo, hero image), slug, contact info
2. `programs` — Loyalty programs (POINTS or STAMPS) belonging to a company, with flexible JSON settings
3. `users` — App users (customers + staff), email/password auth via NestJS, optional Google/Apple OAuth IDs
4. `memberships` — A user's enrollment in a program: wallet ID, balance, status. Unique per user+program
5. `loyalty_history` — Audit log of every balance change (earn, redeem, adjust, etc.) with actor tracking
6. `wallet_passes` — Tracks Google/Apple wallet pass state per membership (external ID, sync status, errors)

## Enums
- ProgramType: POINTS | STAMPS
- MembershipStatus: ACTIVE | INACTIVE | SUSPENDED | DELETED
- LoyaltyEventType: JOIN | EARN | REDEEM | ADJUST | REFUND | EXPIRE | ADMIN_OVERRIDE | WEBHOOK
- WalletProviderType: GOOGLE | APPLE
- WalletPassStatus: PENDING | ACTIVE | UPDATED | FAILED | REVOKED

## Relationships
- Company 1→N Programs, Memberships
- Program 1→N Memberships
- User 1→N Memberships
- Membership 1→N LoyaltyHistory
- Membership 1→1 WalletPass

## Security (RLS)
RLS is enabled on all tables. Since this app uses NestJS + Prisma with its own JWT auth
(not Supabase auth), the backend connects with the service role key which bypasses RLS.
Policies are set to allow anon+authenticated access as a baseline — the NestJS backend
enforces authorization at the application layer (company scoping, JWT user identity).

## Notes
1. Primary keys are TEXT (CUIDs generated by Prisma client at insert time)
2. Timestamps use TIMESTAMP(3) to match Prisma's default precision
3. All foreign keys use ON DELETE CASCADE to match Prisma schema
4. Unique constraints: company slug, user email, membership walletId, user+program per membership
5. Indexes on all frequently-queried columns (slug, companyId, walletId, userId, email, externalId, createdAt)
*/

