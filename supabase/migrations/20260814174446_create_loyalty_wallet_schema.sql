CREATE TYPE "WalletProviderType" AS ENUM ('GOOGLE', 'APPLE');

CREATE TYPE "WalletPassStatus" AS ENUM ('PENDING', 'ACTIVE', 'UPDATED', 'FAILED', 'REVOKED');

-- ─────────────────────────────────────────────
-- companies
-- ─────────────────────────────────────────────
CREATE TABLE IF NOT EXISTS "companies" (
