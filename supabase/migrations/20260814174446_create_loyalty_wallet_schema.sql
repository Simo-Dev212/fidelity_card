    "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "programs_pkey" PRIMARY KEY ("id")
);

CREATE INDEX IF NOT EXISTS "programs_companyId_idx" ON "programs"("companyId");
CREATE UNIQUE INDEX IF NOT EXISTS "programs_companyId_slug_key" ON "programs"("companyId", "slug");

-- ─────────────────────────────────────────────
-- users
-- ─────────────────────────────────────────────
